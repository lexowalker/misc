MOVEMENTS = [("Deep",0),("Memory",16.75),("Star",32),("Silence",48),("Ruin",50.5),("Journey",76),("One drop",98.5),("Metamorphosis",112),("Beauty",128.75),("Last transmission",144),("New mind",159),]
def build():
    out=[]
    for line in T.strip().splitlines():
        sec,rest=line.split(":")
        for tok in rest.split():
            k,t=tok.split("@"); k=int(k)
            out.append({"id":f"{sec}_{k:02d}","text":cues(sec)[k],"t":float(t)})
    out.sort(key=lambda c:c["t"])
    for a,b in zip(out,out[1:]+[{"t":END}]): a["dur"]=round(b["t"]-a["t"],3)
    assert all(c["dur"]>0 for c in out)
    return out
if __name__=="__main__":
    tl=build(); json.dump({"end":END,"movements":MOVEMENTS,"cues":tl},open("timeline.json","w"),indent=0)
    print(len(tl),"cues; min dur",min(c["dur"] for c in tl))
