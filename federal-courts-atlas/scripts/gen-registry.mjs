// Regenerates src/data/registry.ts from the pipeline's canonical registry
// (pipeline/common/districts.py), so the front end never hand-copies district names.
// Usage: npm run gen:registry
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const py = `
import json, sys
sys.path.insert(0, '.')
from pipeline.common.districts import DISTRICTS
print(json.dumps([[d.id, d.name, d.short, d.state, d.state_name, d.circuit, d.article] for d in DISTRICTS]))
`;
const rows = JSON.parse(execFileSync('python3', ['-c', py], { encoding: 'utf8' }));
if (rows.length !== 94) throw new Error(`expected 94 districts, got ${rows.length}`);
const body = rows.map((r) => '  ' + JSON.stringify(r) + ',').join('\n');
const out = `// GENERATED by scripts/gen-registry.mjs from pipeline/common/districts.py. Do not edit by hand.
// Statutory facts only (names, states, circuits): 28 U.S.C. §§ 41, 81-131; 48 U.S.C. §§ 1424, 1611, 1821.
// No statistics live here.

export type RegistryRow = [id: string, name: string, short: string, state: string, stateName: string, circuit: string, article: 'III' | 'IV'];

export const REGISTRY_ROWS: readonly RegistryRow[] = [
${body}
];
`;
writeFileSync('src/data/registry.ts', out);
console.log(`wrote src/data/registry.ts (${rows.length} districts)`);
